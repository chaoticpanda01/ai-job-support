@pytest.mark.asyncio
async def test_generate_rirekisho_returns_output() -> None:
    doc = _mock_document(DocumentType.rirekisho)
    resume = _mock_resume()
    user = _mock_user()
    profile = _mock_profile()

    generator = DocumentGenerator()

    with (
        patch("app.services.document_generator.DocumentRepository") as MockDocRepo,
        patch("app.services.document_generator.ResumeRepository") as MockResumeRepo,
        patch("app.services.document_generator.ProfileRepository") as MockProfileRepo,
        patch("app.services.document_generator.UserRepository") as MockUserRepo,
        patch.object(generator, "_fetch_and_extract", new=AsyncMock(return_value="resume text")),
        patch("app.services.document_generator.usage_tracker.check_budget", new=AsyncMock()),
        patch.object(
            generator,
            "_call_ai",
            new=AsyncMock(return_value=('{"ok": true}', 1200, 800)),
        ),
        patch.object(
            generator,
            "_parse_response",
            return_value=_rirekisho_content(),
        ),
        patch("app.services.document_generator.html_to_pdf", return_value=b"%PDF"),
        patch(
            "app.services.document_generator.file_storage.upload_document",
            return_value="documents/u/rirekisho/abc.pdf",
        ),
        patch("app.services.document_generator.usage_tracker.record", new=AsyncMock()),
    ):
        MockDocRepo.return_value.get = AsyncMock(return_value=doc)
        MockResumeRepo.return_value.get_owned = AsyncMock(return_value=resume)
        MockProfileRepo.return_value.get_by_user_id = AsyncMock(return_value=profile)
        MockUserRepo.return_value.get = AsyncMock(return_value=user)

        result = await generator.generate(doc.id, doc.user_id, AsyncMock())

    assert isinstance(result, GeneratedDocumentOutput)
    assert result.file_url == "documents/u/rirekisho/abc.pdf"
    assert result.input_tokens == 1200
    assert result.output_tokens == 800

    # Personal info came from User/Profile, not from the (garbage) mocked
    # Gemini response — proves the DB-assembly path, not LLM output.
    assert result.content["personal"]["name_kanji"] == "山田 太郎"
    assert result.content["personal"]["name_kana"] == "ヤマダ タロウ"
    assert result.content["personal"]["date_of_birth"] == "平成2年1月15日"
    assert result.content["personal"]["gender"] == "男性"
    assert result.content["personal"]["email"] == "test@example.com"
    # Age is computed as of today, so recompute the expected value the same
    # way rather than hardcoding a number that would go stale over time.
    dob = date(1990, 1, 15)
    today = date.today()
    expected_age = today.year - dob.year - ((today.month, today.day) < (dob.month, dob.day))
    assert result.content["personal"]["age"] == expected_age
    assert result.content["visa_info"]["nationality"] == "インドネシア"
    assert result.content["visa_info"]["visa_category"] is None


